/* Language of the HA user: the panel is same-origin with the HA frontend
 * (Ingress), so the HA language is read from the parent page or from the
 * frontend's localStorage; then the browser; fallback English. */
function detectLang() {
  const pick = (l) => (l || "").toLowerCase().slice(0, 2);
  const cands = [];
  try { cands.push(window.parent.document.querySelector("home-assistant").hass.language); } catch (e) { /* not available */ }
  try { cands.push(JSON.parse(window.localStorage.getItem("selectedLanguage"))); } catch (e) { /* not available */ }
  cands.push(...(navigator.languages || [navigator.language]));
  for (const c of cands) { if (I18N[pick(c)]) return pick(c); }
  return "en";
}
const LANG = detectLang();

/* Translate a key, interpolating {param} placeholders; unknown keys are
 * returned verbatim so a missing string never breaks the UI. */
function t(key, params) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
